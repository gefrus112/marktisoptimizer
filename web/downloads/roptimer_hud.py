@dataclasses.dataclass
class HudSettings:
    """Settings generated by the ROPTIMER website."""

    app: str = APP_NAME
    version: int = 3
    showFps: bool = True
    showPing: bool = True
    showCpu: bool = True
    showRam: bool = True
    notifications: bool = True
    lowFpsAlert: bool = True
    pingAlert: bool = True
    autoProfile: bool = True
    position: str = "tl"
    opacity: float = 0.94
    accent: str = "#7c5cff"
    gameProfile: str = "roleplay"
    fpsTarget: int = 144
    laptopClass: str = "auto"
    tier: str = "BALANCED"
    robloxUsername: str = ""
    showUsername: bool = True
    sessionNotification: bool = True
    sessionMode: str = "safe"
    optimizationMode: str = "Better FPS"
    graphicsTier: int = 1
    textureTier: int = 1
    theme: str = "Lumina"
    cacheCleanupDays: int = 7
    privacyMode: bool = True
    window_x: int | None = None
    window_y: int | None = None

    @classmethod
    def from_dict(cls, raw: dict[str, Any] | None) -> "HudSettings":
        raw = raw or {}
        known = {f.name for f in dataclasses.fields(cls)}
        values = {k: v for k, v in raw.items() if k in known}
        settings = cls(**values)
        settings.normalize_in_place()
        return settings

    def normalize_in_place(self) -> None:
        for field in (
            "showFps",
            "showPing",
            "showCpu",
            "showRam",
            "notifications",
            "lowFpsAlert",
            "pingAlert",
            "autoProfile",
            "showUsername",
            "sessionNotification",
        ):
            setattr(self, field, bool(getattr(self, field)))
        try:
            self.fpsTarget = max(60, min(9999, int(self.fpsTarget)))
        except (TypeError, ValueError):
            self.fpsTarget = 144
        try:
            self.opacity = max(0.35, min(1.0, float(self.opacity)))
        except (TypeError, ValueError):
            self.opacity = 0.94
        if self.position not in {"tl", "tr", "bl", "br"}:
            self.position = "tl"
        if not isinstance(self.accent, str) or not self.accent.startswith("#") or len(self.accent) != 7:
            self.accent = RED
        if self.gameProfile not in GAME_LABELS:
            self.gameProfile = "roleplay"
        try:
            self.version = max(1, int(self.version))
        except (TypeError, ValueError):
            self.version = 1
        self.tier = str(self.tier or "BALANCED")[:16]
        self.laptopClass = str(self.laptopClass or "auto")[:24]
        self.robloxUsername = "".join(
            ch for ch in str(self.robloxUsername or "") if ch.isprintable()
        ).strip()[:32]
        self.sessionMode = "safe" if str(self.sessionMode or "safe") != "unsafe" else "safe"
        self.optimizationMode = str(self.optimizationMode or "Better FPS")[:40]
        try:
            self.graphicsTier = max(0, min(21, int(self.graphicsTier)))
        except (TypeError, ValueError):
            self.graphicsTier = 1
        try:
            self.textureTier = max(0, min(3, int(self.textureTier)))
        except (TypeError, ValueError):
            self.textureTier = 1
        try:
            self.cacheCleanupDays = max(1, min(90, int(self.cacheCleanupDays)))
        except (TypeError, ValueError):
            self.cacheCleanupDays = 7
        self.theme = str(self.theme or "Lumina")[:24]
        self.privacyMode = bool(self.privacyMode)
        for field in ("window_x", "window_y"):
            value = getattr(self, field)
            if value is not None:
                try:
                    setattr(self, field, int(value))
                except (TypeError, ValueError):
                    setattr(self, field, None)

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


def settings_search_paths(explicit: str | None = None) -> list[Path]:
    """Return locations where hud-settings.json may live."""
    paths: list[Path] = []
    if explicit:
        paths.append(Path(explicit).expanduser())
    paths.append(Path.cwd() / SETTINGS_FILE)
    paths.append(Path(__file__).with_name(SETTINGS_FILE))
    appdata = os.getenv("APPDATA")
    if appdata:
        paths.append(Path(appdata) / "Roptimer" / SETTINGS_FILE)
    else:
        paths.append(Path.home() / ".config" / "Roptimer" / SETTINGS_FILE)

    unique: list[Path] = []
    seen: set[str] = set()
    for path in paths:
        key = str(path.resolve()) if path.exists() else str(path)
        if key not in seen:
            seen.add(key)
            unique.append(path)
    return unique


def load_settings(explicit: str | None = None) -> tuple[HudSettings, Path | None]:
    """Load the first available settings file, or return defaults."""
    for path in settings_search_paths(explicit):
        try:
            if path.is_file():
                raw = json.loads(path.read_text(encoding="utf-8-sig"))
                if isinstance(raw, dict):
                    return HudSettings.from_dict(raw), path
        except (OSError, ValueError, json.JSONDecodeError):
            continue
    return HudSettings(), None


def default_settings_path() -> Path:
    appdata = os.getenv("APPDATA")
    base = Path(appdata) / "Roptimer" if appdata else Path.home() / ".config" / "Roptimer"
    return base / SETTINGS_FILE


def save_settings(settings: HudSettings, path: Path | None = None) -> Path:
    """Persist settings for the next HUD launch."""
    target = Path(path) if path else default_settings_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = settings.to_dict()
    payload["saved_at"] = dt.datetime.now().isoformat(timespec="seconds")
    target.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return target


def measure_ping(host: str = PING_HOST, port: int = PING_PORT, timeout: float = 2.0) -> float | None:
    """Measure TCP connection latency in milliseconds without sending game data."""
    start = time.perf_counter()
    sock: socket.socket | None = None
    try:
        sock = socket.create_connection((host, port), timeout=timeout)
        return (time.perf_counter() - start) * 1000.0
    except (OSError, socket.timeout, ValueError):
        return None
    finally:
        if sock is not None:
            try:
                sock.close()
            except OSError:
                pass


class SystemHints:
    """Optional CPU/RAM hints via psutil; never accesses Roblox memory."""

    def __init__(self) -> None:
        self.psutil = None
        try:
            import psutil  # type: ignore

            self.psutil = psutil
        except ImportError:
            pass

    def cpu_percent(self) -> str:
        if self.psutil is None:
            return "n/a"
        try:
            return f"{float(self.psutil.cpu_percent(interval=None)):.0f}%"
        except Exception:
            return "n/a"

    def memory_percent(self) -> str:
        if self.psutil is None:
            return "n/a"
        try:
            return f"{float(self.psutil.virtual_memory().percent):.0f}%"
        except Exception:
            return "n/a"


def run_self_test() -> int:
    """Headless tests for settings parsing and the TCP ping helper."""
    sample = {
        "app": "Roptimer HUD V3",
        "version": 3,
        "showFps": True,
        "showPing": True,
        "showCpu": False,
        "showRam": False,
        "notifications": True,
        "lowFpsAlert": True,
        "pingAlert": True,
        "autoProfile": True,
        "position": "tr",
        "opacity": 0.8,
        "accent": "#ff003c",
        "gameProfile": "fps",
        "fpsTarget": 999,
        "laptopClass": "gaming",
        "tier": "HIGH",
        "robloxUsername": "ROPTIMER_V3_1_USER",
        "showUsername": True,
        "sessionNotification": True,
        "sessionMode": "safe",
        "optimizationMode": "Better FPS",
        "graphicsTier": 1,
        "textureTier": 1,
        "theme": "Lumina",
        "cacheCleanupDays": 7,
        "privacyMode": True,
    }
    settings = HudSettings.from_dict(sample)
    assert settings.position == "tr"
    assert settings.fpsTarget == 999
    assert settings.gameProfile == "fps"
    assert settings.accent == "#ff003c"
    assert settings.showCpu is False
    assert settings.robloxUsername == "ROPTIMER_V3_1_USER"
    assert settings.sessionMode == "safe"
    assert settings.version == 3
    assert settings.graphicsTier in range(22)
    assert settings.textureTier in range(4)
    assert settings.theme

    # Use a local throwaway TCP server to test measure_ping without internet.
    server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    server.bind(("127.0.0.1", 0))
    server.listen(1)
    port = server.getsockname()[1]
    errors: list[Exception] = []

    def accept_once() -> None:
        try:
            conn, _ = server.accept()
            conn.close()
        except Exception as exc:  # noqa: BLE001
            errors.append(exc)
        finally:
            try:
                server.close()
            except OSError:
                pass

    thread = threading.Thread(target=accept_once, daemon=True)
    thread.start()
    latency = measure_ping("127.0.0.1", port, timeout=1.5)
    thread.join(timeout=2.0)
    assert latency is not None and latency >= 0.0, latency
    assert not errors, errors

    # Round-trip persistence.
    with tempfile.TemporaryDirectory(prefix="roptimer-hud-") as tmp:
        path = Path(tmp) / "nested" / SETTINGS_FILE
        saved = save_settings(settings, path)
        loaded, source = load_settings(str(saved))
        assert source == saved
        assert loaded.position == settings.position
        assert loaded.fpsTarget == settings.fpsTarget

    print(f"ROPTIMER HUD SELF-TEST OK: settings parsed, local ping {latency:.2f} ms, persistence verified.")
    return 0


