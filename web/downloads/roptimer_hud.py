"""
ROPTIMER HUD — safe always-on-top performance companion
=======================================================

A small, separate desktop window for the Roptimzier project. It displays:

  * your configured FPS target (it does NOT read Roblox game memory),
  * a real TCP latency measurement to a Roblox endpoint,
  * optional CPU/RAM system hints via the optional ``psutil`` package,
  * notifications, position, opacity and game-profile preferences.

It does NOT inject into Roblox, hook the renderer, read game memory, automate
gameplay, bypass anti-cheat, or alter Roblox processes. For real in-game FPS
and server ping, use Roblox's own Performance Stats / Debug Stats overlays.

Run:
    python roptimer_hud.py

Use a settings file generated by web/index.html:
    python roptimer_hud.py --settings hud-settings.json

Headless test:
    python roptimer_hud.py --self-test

Optional dependency:
    python -m pip install psutil
"""

