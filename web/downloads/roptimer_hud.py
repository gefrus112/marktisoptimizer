        def _apply_row_visibility(self) -> None:
            visibility = {
                "mode": True,
                "user": self.settings.showUsername,
                "fps": self.settings.showFps,
                "ping": self.settings.showPing,
                "cpu": self.settings.showCpu,
                "ram": self.settings.showRam,
                "hz": True,
            }
            for key, (row, _value) in self.rows.items():
                if visibility.get(key, True):
                    row.pack(fill="x", pady=3)
                else:
                    row.pack_forget()

        # -- placement / dragging -----------------------------------------

        def _place_window(self) -> None:
            self.update_idletasks()
            width = max(self.winfo_reqwidth(), 285)
            height = max(self.winfo_reqheight(), 270)
            screen_w = self.winfo_screenwidth()
            screen_h = self.winfo_screenheight()
            margin = 18
            if self.settings.window_x is not None and self.settings.window_y is not None:
                x = max(0, min(screen_w - width, int(self.settings.window_x)))
                y = max(0, min(screen_h - height, int(self.settings.window_y)))
            else:
                position = self.settings.position
                x = margin if position in {"tl", "bl"} else screen_w - width - margin
                y = margin if position in {"tl", "tr"} else screen_h - height - margin
            self.geometry(f"{width}x{height}+{x}+{y}")

        def _start_drag(self, event: Any) -> None:
            self.drag_x = event.x
            self.drag_y = event.y

        def _on_drag(self, event: Any) -> None:
            x = self.winfo_pointerx() - self.drag_x
            y = self.winfo_pointery() - self.drag_y
            self.geometry(f"+{x}+{y}")

        # -- data ----------------------------------------------------------

        def ping_now(self) -> None:
            if self.ping_thread and self.ping_thread.is_alive():
                self._notify("A ping test is already running.")
                return
            self.rows["ping"][1].configure(text="measuring…")

            def worker() -> None:
                latency = measure_ping()
                self.queue.put(("ping", latency))

            self.ping_thread = threading.Thread(target=worker, daemon=True)
            self.ping_thread.start()
            self.last_ping = time.monotonic()

        def _tick(self) -> None:
            now = time.perf_counter()
            self.hud_frames += 1
            elapsed = now - self.last_tick
            if elapsed >= 1.0:
                self.hud_hz = self.hud_frames / elapsed
                self.hud_frames = 0
                self.last_tick = now
                self.rows["hz"][1].configure(text=f"{self.hud_hz:.0f} Hz")
                self.rows["cpu"][1].configure(text=self.system.cpu_percent())
                self.rows["ram"][1].configure(text=self.system.memory_percent())

            if time.monotonic() - self.last_ping >= 5.0:
                self.ping_now()
            self.after(1000, self._tick)

        def _drain_queue(self) -> None:
            try:
                while True:
                    kind, value = self.queue.get_nowait()
                    if kind == "ping":
                        if value is None:
                            self.rows["ping"][1].configure(text="offline")
                            self._notify("Ping test could not reach the Roblox endpoint.")
                        else:
                            latency = float(value)
                            self.rows["ping"][1].configure(text=f"{latency:.0f} ms")
                            if self.settings.pingAlert and latency > 150:
                                self._notify("High network latency detected. Try a wired connection.")
                            elif self.settings.lowFpsAlert:
                                self._notify("If gameplay stutters, open Roblox built-in stats to check real FPS.")
            except queue.Empty:
                pass
            self.after(200, self._drain_queue)

        def _notify(self, message: str) -> None:
            if not self.settings.notifications:
                return
            if message == self.last_notification:
                return
            self.last_notification = message
            timestamp = dt.datetime.now().strftime("%H:%M:%S")
            self.notification.configure(text=f"{timestamp}  {message}")

        # -- actions -------------------------------------------------------

        def copy_stats(self) -> None:
            lines = [
                f"{APP_NAME} v{APP_VERSION}",
                f"Mode: {self.settings.optimizationMode} / graphics tier {self.settings.graphicsTier}",
                f"Display name: {self.settings.robloxUsername or self._local_username()}",
                f"FPS target: {self.settings.fpsTarget}",
                f"Ping: {self.rows['ping'][1].cget('text')}",
                f"CPU: {self.rows['cpu'][1].cget('text')}",
                f"RAM: {self.rows['ram'][1].cget('text')}",
                f"Profile: {GAME_LABELS.get(self.settings.gameProfile, self.settings.gameProfile)}",
                "Note: FPS is a target, not a memory-read in-game FPS value.",
            ]
            self.clipboard_clear()
            self.clipboard_append("\n".join(lines))
            self._notify("Stats copied to clipboard.")

        def open_stats_guide(self) -> None:
            webbrowser.open(STATS_GUIDE_URL)
            self._notify("Opened Roblox's official performance stats guide.")

        def hide_temporarily(self) -> None:
            if self.hidden:
                return
            self.hidden = True
            self.withdraw()
            self.after(10000, self._show_again)
            self._notify("HUD hidden for 10 seconds.")

        def _show_again(self) -> None:
            self.hidden = False
            try:
                self.deiconify()
                self.attributes("-topmost", True)
            except tk.TclError:
                pass

        def close(self) -> None:
            try:
                geometry = self.geometry()
                # Example: 300x280+40+30
                plus = geometry.rfind("+")
                if plus != -1:
                    coords = geometry[plus + 1 :].split("+")
                    if len(coords) == 2:
                        self.settings.window_x = int(coords[0])
                        self.settings.window_y = int(coords[1])
            except (ValueError, tk.TclError):
                pass
            save_settings(self.settings, self.settings_path)
            self.destroy()


