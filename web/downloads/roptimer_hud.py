def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="roptimer_hud.py",
        description="ROPTIMER HUD — safe separate performance window for Roblox settings.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {APP_VERSION}")
    parser.add_argument("--features", action="store_true", help="print the shared V3.2 feature catalog and exit")
    parser.add_argument("--build-info", action="store_true", help="print build and safety information and exit")
    parser.add_argument("--settings", help="path to hud-settings.json")
    parser.add_argument("--self-test", action="store_true", help="run headless tests and exit")
    parser.add_argument("--no-gui", action="store_true", help="print loaded settings and exit")
    parser.add_argument("--print-defaults", action="store_true", help="print default settings JSON and exit")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    if args.self_test:
        return run_self_test()
    if args.features:
        catalog_path = Path(__file__).with_name("feature-status.json")
        print(catalog_path.read_text(encoding="utf-8") if catalog_path.is_file() else '{"features":[],"sources":[]}')
        return 0
    if args.build_info:
        print(json.dumps({
            "app": APP_NAME,
            "version": APP_VERSION,
            "dotnetApp": "3.0.0",
            "safety": {"injection": False, "memoryReads": False, "telemetryDisable": False, "antiCheatBypass": False},
        }, indent=2))
        return 0
    if args.print_defaults:
        print(json.dumps(HudSettings().to_dict(), indent=2))
        return 0

    settings, source = load_settings(args.settings)
    if args.no_gui:
        print(json.dumps({"source": str(source) if source else None, "settings": settings.to_dict()}, indent=2))
        return 0

    if not HAS_TK:
        print(
            f"Tkinter is unavailable ({TK_IMPORT_ERROR}). Use a Python build with Tkinter, "
            "or try --self-test / --no-gui.",
            file=sys.stderr,
        )
        return 1

    print(f"{APP_NAME} v{APP_VERSION} — settings: {source or 'defaults'}")
    print("Separate window only. No injection, no memory reads, no automation.")
    try:
        app = HudApp(settings, source)
        app.mainloop()
    except tk.TclError as exc:  # pragma: no cover - no display
        print(f"Could not open the HUD window: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
